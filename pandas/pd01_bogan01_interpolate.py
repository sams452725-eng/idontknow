'''
결측치 처리
1. 삭제 - 행 또는 열 전체
2. 임의의 값
    - 0 : fillna
    - 평균값 : mean(특히 이상치 조심)
    - 중위값 : median
    - 앞전값 : ffill
    - 뒷값 : bfill
    - 특정값 : 아무거나 임의 값(777,333,999)
    - 최빈값
    - 기타등등..
3. interpolate - 보간법(알려진 데이터 점 집합의 범위 내에 새 데이터 점을 추가하는 기법)
4. 모델 : .predict(값을 예측 후 다른 전혀 다른 모델에 사용)
5. 부스팅(트리) 계열 모델 : 통상 결측치, 이상치에 대해 영향을 덜 받는다.(자유롭다.)
    - XGBoost, LightGBM, CatBoost 등 일부 머신러닝 알고리즘은 내부적으로 결측치를 학습 과정에서 최적의 방향으로 처리
6. 스케일링(로브스트 등) - 이상치에 자유롭다.
'''

import pandas as pd
import numpy as np
# print(pd.__version__)       #3.0.6

dates=[
    '11/11/2026', '12/11/2026', '13/11/2026', 
    '14/11/2026', '15/11/2026', '16/11/2026', 
    '17/11/2026', '18/11/2026', '19/11/2026', 
]
dates=pd.to_datetime(dates,dayfirst=True)
# print(dates)

# DatetimeIndex(['2026-11-11', '2026-11-12', '2026-11-13', '2026-11-14',
#                '2026-11-15', '2026-11-16', '2026-11-17', '2026-11-18',
#                '2026-11-19'],
#               dtype='datetime64[us]', freq=None)
print('='*100)
ts=pd.Series([0,2,np.nan,np.nan,8,10,np.nan,14,16], index=dates)    #ts=time_series
# print(ts)
# 2026-11-11     0.0
# 2026-11-12     2.0
# 2026-11-13     NaN
# 2026-11-14     NaN
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17     NaN
# 2026-11-18    14.0
# 2026-11-19    16.0
# dtype: float64

print('='*100)
ts=ts.interpolate()
print(ts)
# 2026-11-11     0.0
# 2026-11-12     2.0
# 2026-11-13     4.0
# 2026-11-14     6.0
# 2026-11-15     8.0
# 2026-11-16    10.0
# 2026-11-17    12.0
# 2026-11-18    14.0
# 2026-11-19    16.0
# dtype: float64

# 중간값들은 linear로 채워짐.
# 마지막 값이 결측인 경우 ffill
# 첫전째 값이 결측인 경우에는 자동으로 처리 안됨.(수동으로 평균이든 0이든 특정 값을 직접 처리해야됨.)